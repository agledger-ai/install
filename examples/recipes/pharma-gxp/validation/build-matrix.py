#!/usr/bin/env python3
"""Build TRACEABILITY.md from REQUIREMENTS.json.

Each requirement maps to the contract type or engine rule that satisfies it and to the
assertions a scripted OQ makes. Pass the log of an OQ run as the first argument to mark
each requirement with the assertions that run proved: the log is one line per assertion,
`<requirement id><TAB><assertion text>`, and a requirement with no line prints UNCOVERED
and the build exits non-zero. Without a log the matrix lists what the OQ has to assert.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
reqs = json.load(open(os.path.join(HERE, "REQUIREMENTS.json")))

proved = {}
log = sys.argv[1] if len(sys.argv) > 1 else None
if log:
    for line in open(log):
        rid, _, text = line.rstrip("\n").partition("\t")
        if rid and text:
            proved.setdefault(rid, []).append(text)

out = ["# Traceability matrix: requirement, control, OQ assertion", "",
       "Generated by `validation/build-matrix.py` from `REQUIREMENTS.json`"
       + (" and the OQ log `%s`" % os.path.basename(log) if log else "")
       + ". Do not edit by hand.", "",
       "| Req | Requirement | Satisfied by | %s |" % ("Proven by (OQ run)" if log else "The OQ asserts"),
       "|---|---|---|---|"]
uncovered = 0
for r in reqs["requirements"]:
    if log:
        labels = proved.get(r["id"], [])
        if not labels:
            uncovered += 1
            labels = ["**UNCOVERED**"]
    else:
        labels = r.get("oqAsserts", [])
    out.append("| %s | %s | %s | %s |" % (r["id"], r["text"], r["satisfiedBy"], "<br>".join(labels)))

if log:
    unmapped = sorted(set(proved) - {r["id"] for r in reqs["requirements"]})
    out += ["", "## OQ assertions not mapped to a requirement", ""]
    out += ["- `%s` %s" % (rid, "; ".join(proved[rid])) for rid in unmapped] or ["(none)"]
    out += ["", "%d requirement(s), %d uncovered." % (len(reqs["requirements"]), uncovered)]
else:
    n = sum(len(r.get("oqAsserts", [])) for r in reqs["requirements"])
    out += ["", "%d requirement(s), %d OQ assertions to make." % (len(reqs["requirements"]), n)]

open(os.path.join(HERE, "TRACEABILITY.md"), "w").write("\n".join(out) + "\n")
print(out[-1])
sys.exit(0 if uncovered == 0 else 1)
